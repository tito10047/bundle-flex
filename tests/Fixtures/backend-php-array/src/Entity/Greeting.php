<?php

declare(strict_types=1);

namespace Acme\BackendPhpArrayBundle\Entity;

/**
 * A greeting sent to someone, stored in the "acme_backend_php_array_greeting" table.
 *
 * The entity is a plain PHP class: its Doctrine mapping is defined in config/doctrine/Greeting.orm.xml,
 * so applications can override it. It is not final: Doctrine extends it to create its lazy-loading proxies.
 */
class Greeting
{
    private ?int $id = null;

    private readonly \DateTimeImmutable $createdAt;

    /**
     * @param string                  $name      the name of the person greeted, e.g. "Jane"
     * @param string                  $message   the greeting, e.g. "Hello Jane!"
     * @param \DateTimeImmutable|null $createdAt when the greeting was sent, now by default
     */
    public function __construct(
        private readonly string $name,
        private readonly string $message,
        ?\DateTimeImmutable $createdAt = null,
    ) {
        $this->createdAt = $createdAt ?? new \DateTimeImmutable();
    }

    /**
     * The identifier generated by the database, null until the greeting is persisted and flushed.
     */
    public function getId(): ?int
    {
        return $this->id;
    }

    public function getName(): string
    {
        return $this->name;
    }

    public function getMessage(): string
    {
        return $this->message;
    }

    public function getCreatedAt(): \DateTimeImmutable
    {
        return $this->createdAt;
    }
}
